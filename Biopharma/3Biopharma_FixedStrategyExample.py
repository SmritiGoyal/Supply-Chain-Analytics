# Part 3 — Evaluate 3 fixed network strategies
#
# Each strategy fixes plant/line open decisions (Plant, H, R) and optimizes only shipment flows (Highcal, Relax)
# under 100 FX scenarios. We report expected cost and standard deviation.

plants = list(caps.index)  # ['Brazil','Germany','India','Japan','Mexico','U.S.']
lines  = ["Plant","H","R"]

def strategy_from_open_rates(open_rate_series, threshold_plant=0.5, threshold_line=0.5):
    """Build a 6x3 strategy matrix (order = plants, cols = Plant/H/R) from open-rate series."""
    mat = np.zeros((len(plants), 3), dtype=int)
    for i,p in enumerate(plants):
        for j,l in enumerate(lines):
            key = f"{p}_{l}" if l!="Plant" else f"{p}_Plant"
            rate = float(open_rate_series.get(key, 0.0))
            thr = threshold_plant if l=="Plant" else threshold_line
            mat[i,j] = int(rate >= thr)
    return mat

