# ---- Evaluation function ----
def eval_fixed_strategy(dec_plant_fixed, fx_draws_eval):
    # Build LP once for this fixed network
    model = Model("FixedNetwork")
    model.Params.OutputFlag = 0

    # Decision variables: shipments from plant i to market j for Highcal and Relax
    dec_h = {(i, j): model.addVar(vtype=GRB.CONTINUOUS, lb=0, name=f"Dec_h_{i}_{j}") for i in n_ctry for j in n_ctry}
    dec_r = {(i, j): model.addVar(vtype=GRB.CONTINUOUS, lb=0, name=f"Dec_r_{i}_{j}") for i in n_ctry for j in n_ctry}

    # Constraints: capacity and demand satisfaction (reuse helper functions from earlier cells)
    excess_cap = calc_excess_cap(dec_plant_fixed, dec_h, dec_r)
    for i in n_ctry:
        for j in range(3):  # Plant, H, R
            model.addConstr(excess_cap[i, j] >= 0, name=f"Cap_{i}_{j}")

    unmet = calc_unmet_demand(dec_h, dec_r)
    for i in n_ctry:
        for j in range(2):  # Highcal, Relax
            model.addConstr(unmet[i, j] == 0, name=f"Demand_{i}_{j}")

    model.update()

    costs = []
    for s in range(len(fx_draws_eval)):
        # Update global exrate for this scenario (selected_yr column is overwritten)
        global exrate
        exrate = exrate0.copy()
        draw = fx_draws_eval.loc[s, ["BRL","EUR","INR","JPY","MXN","USD"]].values
        exrate.loc[:, f"{selected_yr}"] = draw

        model.setObjective(calc_total_cost(dec_plant_fixed, dec_h, dec_r, base_yr, selected_yr, tariff), GRB.MINIMIZE)
        model.optimize()
        costs.append(float(model.objVal))

    costs = np.array(costs, dtype=float)
    return costs.mean(), costs.std(ddof=1), costs

