# ----------------------------
# Configuration (no user input)
# ----------------------------
base_yr = 2019
selected_yr = 2023
tariff = 0.0          # set >0 if you want to evaluate a tariff scenario
n_scenarios = 100
seed = 123

# ----------------------------
# Load FX draws
# ----------------------------
fx_path = "fx_draws_100.csv"
if not os.path.exists(fx_path):
    raise FileNotFoundError(
        f"Missing {fx_path}. Run getExchangeRates_Frankfurter_COMPLETED.ipynb first "
        "to generate fx_draws_100.csv, then rerun this notebook."
    )

fx_draws = pd.read_csv(fx_path)
expected_cols = ["BRL","EUR","INR","JPY","MXN","USD"]
missing = [c for c in expected_cols if c not in fx_draws.columns]
if missing:
    raise ValueError(f"{fx_path} must contain columns {expected_cols}. Missing: {missing}")

# Keep exactly n_scenarios rows (in case file has more)
fx_draws = fx_draws.loc[:n_scenarios-1, expected_cols].copy()

# ----------------------------
# Build the optimization model ONCE
# ----------------------------
model = Model("Biopharma_ScenarioOptimization")
model.Params.OutputFlag = 0

# Decision variables
# Plant/line open decisions: (plant i) x (line j) where j = 0:Plant, 1:H, 2:R
dec_plant = {(i, j): model.addVar(vtype=GRB.BINARY, name=f"Dec_Plant_{i}_{j}")
             for i in n_ctry for j in n_lines}

# Flows for high and relaxed products: i -> j (plant i ships to market j)
dec_h = {(i, j): model.addVar(vtype=GRB.CONTINUOUS, lb=0, name=f"Dec_H_{i}_{j}")
         for i in n_ctry for j in n_ctry}
dec_r = {(i, j): model.addVar(vtype=GRB.CONTINUOUS, lb=0, name=f"Dec_R_{i}_{j}")
         for i in n_ctry for j in n_ctry}

# Constraints
# 1) Capacity (total, H line, R line) via excess capacity expression
excess_cap = calc_excess_cap(dec_plant, dec_h, dec_r)
for i in n_ctry:
    for j in n_lines:
        model.addConstr(excess_cap[i, j] >= 0, name=f"Cap_{i}_{j}")

# 2) Demand must be met exactly (unmet_demand == 0) for both H and R
unmet = calc_unmet_demand(dec_h, dec_r)
for i in n_ctry:
    for j in range(2):
        model.addConstr(unmet[i, j] == 0, name=f"Dem_{i}_{j}")

# 3) Logical linking: if line open then plant open (H->Plant, R->Plant)
#    dec_plant[i,0] is "Plant open", dec_plant[i,1] is "H line open", dec_plant[i,2] is "R line open"
for i in n_ctry:
    model.addConstr(dec_plant[i,1] <= dec_plant[i,0], name=f"Link_H_{i}")
    model.addConstr(dec_plant[i,2] <= dec_plant[i,0], name=f"Link_R_{i}")

model.update()

# ----------------------------
# Scenario loop: update exrate and objective, solve, and record open decisions
# ----------------------------
results = []
np.random.seed(seed)

for s in range(n_scenarios):
    # Update the exchange rates for the scenario by overwriting the 'selected_yr' column
    # exrate is a GLOBAL used by calc_total_cost()
    exrate = exrate0.copy()
    exrate.loc[:, f"{selected_yr}"] = fx_draws.loc[s, expected_cols].values

    # Update objective (scenario-specific)
    model.setObjective(calc_total_cost(dec_plant, dec_h, dec_r, base_yr, selected_yr, tariff), GRB.MINIMIZE)

    # Optimize
    model.optimize()

    # Record results
    row = {"scenario": s, "total_cost": float(model.objVal)}
    # Save plant/line decisions in a tidy way: PlantName_{Plant/H/R}
    plant_names = list(caps.index)  # ['Brazil','Germany','India','Japan','Mexico','U.S.']
    for idx, plant in enumerate(plant_names):
        row[f"{plant}_Plant"] = int(dec_plant[idx,0].X > 0.5)
        row[f"{plant}_H"]     = int(dec_plant[idx,1].X > 0.5)
        row[f"{plant}_R"]     = int(dec_plant[idx,2].X > 0.5)
    results.append(row)

res_df = pd.DataFrame(results)

# Save Part 1 results
res_df.to_csv("biopharma_part1_results_res_df.csv", index=False)

print("Part 1 complete: wrote biopharma_part1_results_res_df.csv")
print(res_df.head())

