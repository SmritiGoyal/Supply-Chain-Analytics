# Part 1 & Part 2: Scenario-based optimization over sampled exchange rates
# ---------------------------------------------------------------------
# This notebook assumes you already generated `fx_draws_100.csv` from the
# completed getExchangeRates notebook and placed it in the same folder
# where you run this notebook.
#
# Output files (written to current working directory):
#   - biopharma_part1_results_res_df.csv
